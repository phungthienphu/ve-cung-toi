import mongoose, { Schema } from 'mongoose';
const edge = new Schema({ key: { type: String, unique: true, required: true }, from: String, to: String, status: { type: String, enum: ['pending', 'accepted'], default: 'pending' } }, { timestamps: true });
const message = new Schema({ from: { type: String, index: true }, to: { type: String, index: true }, text: String, readAt: Date }, { timestamps: true });
message.index({ from: 1, to: 1, createdAt: -1 });
edge.index({ from: 1, to: 1 });
edge.index({ from: 1, status: 1 });
edge.index({ to: 1, status: 1 });
message.index({ from: 1, to: 1, createdAt: -1, _id: -1 });
message.index({ to: 1, from: 1, createdAt: -1, _id: -1 });
message.index({ to: 1, readAt: 1, from: 1 });
const invite = new Schema({ from: String, to: { type: String, index: true }, path: String, expiresAt: Date, readAt: Date }, { timestamps: true });
invite.index({ to: 1, readAt: 1, expiresAt: 1 });
invite.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });
const block = new Schema({ from: String, to: String }); block.index({ from: 1, to: 1 }, { unique: true }); block.index({ to: 1, from: 1 });
const report = new Schema({ from: String, to: String, reason: String }, { timestamps: true });
export const Friendship = mongoose.models.Friendship || mongoose.model('Friendship', edge);
export const ChatMessage = mongoose.models.ChatMessage || mongoose.model('ChatMessage', message);
export const RoomInvite = mongoose.models.RoomInvite || mongoose.model('RoomInvite', invite);
export const PlayerBlock = mongoose.models.PlayerBlock || mongoose.model('PlayerBlock', block);
export const PlayerReport = mongoose.models.PlayerReport || mongoose.model('PlayerReport', report);
const setting = new Schema({ gameId: { type: String, unique: true }, enabled: { type: Boolean, default: true } }, { timestamps: true });
const impression = new Schema({ eventId: { type: String, unique: true }, path: String, day: { type: String, index: true }, expiresAt: Date });
impression.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });
const audit = new Schema({ actor: String, action: String, target: String }, { timestamps: true });
export const GameSetting = mongoose.models.GameSetting || mongoose.model('GameSetting', setting);
export const Impression = mongoose.models.Impression || mongoose.model('Impression', impression);
export const AdminAudit = mongoose.models.AdminAudit || mongoose.model('AdminAudit', audit);
const support = new Schema({ guest: { type: Boolean, default: false }, guestName: String, owner: { type: String, required: true, index: true }, fromAdmin: { type: Boolean, default: false }, text: { type: String, required: true }, readAt: Date }, { timestamps: true });
support.index({ owner: 1, createdAt: -1 });
export const SupportMessage = mongoose.models.SupportMessage || mongoose.model('SupportMessage', support);
